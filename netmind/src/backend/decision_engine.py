"""NetMind AI - Risk Scoring & Rule-Based Recommendation Decision Engine.

Cybersecurity & Mathematical Rationale:
----------------------------------------
1. Multi-Vector Composite Risk Formulation:
   Relying on a single threshold (e.g., high packet rate alone) causes severe alert fatigue.
   NetMind AI fuses four orthogonal telemetry and security dimensions into a composite score:
       Risk = 0.40 * SecurityRisk + 0.25 * AnomalyScore + 0.20 * PerformanceRisk + 0.15 * HistoricalRisk

   Weights Allocation & Domain Justification:
   - SecurityRisk (40%): Direct attack classification (DoS, Brute Force, Web Attack) with confidence scaling.
   - AnomalyScore (25%): Unsupervised Isolation Forest score capturing novel zero-day behavioral drift.
   - PerformanceRisk (20%): Network link and interface stress (bandwidth spikes, packet flood saturation).
   - HistoricalRisk (15%): Host recurrence penalty based on prior quarantine records and past incident frequency.

2. Risk Categorization Tiers:
   - LOW (0 - 25): Nominal enterprise baseline; standard observability.
   - MEDIUM (26 - 50): Elevated telemetry variance; proactive log sampling and analyst awareness.
   - HIGH (51 - 75): Confirmed adversarial technique; automated rate limiting and credential isolation.
   - CRITICAL (76 - 100): High-confidence severe attack; perimeter ACL drop and host quarantine.

3. Human-in-the-Loop Decision Support:
   Security orchestration systems must never automatically sever critical corporate assets without
   verifiable justification. The Decision Engine maps classified vectors to human-reviewable
   containment recommendations (`QUARANTINE_HOST`, `RATE_LIMIT_PORT`, `BLOCK_SOURCE_IP`).
"""

from __future__ import annotations

import logging
from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Tuple

from netmind.src.backend.schemas import (
    EventSeverity,
    RecommendationAction,
    RiskCategory,
)

logger = logging.getLogger(__name__)


@dataclass
class RiskEvaluationResult:
    """Detailed output of the composite risk evaluation."""

    overall_score: float
    risk_category: RiskCategory
    security_risk: float
    anomaly_score: float
    performance_risk: float
    historical_risk: float
    breakdown_rationale: str


@dataclass
class RecommendedMitigation:
    """Structured containment action proposal generated by the Decision Engine."""

    action: RecommendationAction
    action_str: str
    reason: str
    urgency: str  # IMMEDIATE, HIGH, ROUTINE
    target_entity: str  # Source IP, Host, or Service Port
    requires_human_approval: bool = True


class DecisionEngine:
    """Core decision support and automated risk evaluation engine for NetMind AI."""

    # Weights configuration
    W_SECURITY = 0.40
    W_ANOMALY = 0.25
    W_PERFORMANCE = 0.20
    W_HISTORICAL = 0.15

    # Severity base weights for security events
    SEVERITY_BASE_SCORES: Dict[str, float] = {
        "LOW": 20.0,
        "MEDIUM": 45.0,
        "HIGH": 75.0,
        "CRITICAL": 95.0,
    }

    # Attack category base risk scaling
    ATTACK_BASE_SCORES: Dict[str, float] = {
        "Normal": 0.0,
        "DoS": 90.0,
        "Web Attack": 85.0,
        "Brute Force": 70.0,
        "Port Scan": 55.0,
    }

    @classmethod
    def calculate_risk_score(
        cls,
        security_risk: float,
        anomaly_score: float,
        performance_risk: float,
        historical_risk: float,
    ) -> RiskEvaluationResult:
        """Calculate composite risk score based on the four-factor algorithm.

        Args:
            security_risk: Direct threat evidence score in [0, 100].
            anomaly_score: Isolation Forest score scaled to [0, 100].
            performance_risk: Bandwidth/packet saturation score in [0, 100].
            historical_risk: Historical penalty for repeat offender host in [0, 100].

        Returns:
            RiskEvaluationResult: Categorized score and component breakdown.
        """
        # Clamp inputs to [0, 100]
        sec = max(0.0, min(100.0, float(security_risk)))
        anom = max(0.0, min(100.0, float(anomaly_score)))
        perf = max(0.0, min(100.0, float(performance_risk)))
        hist = max(0.0, min(100.0, float(historical_risk)))

        # Mathematical composite equation:
        # Risk = 0.40 * SecurityRisk + 0.25 * AnomalyScore + 0.20 * PerformanceRisk + 0.15 * HistoricalRisk
        composite = (
            cls.W_SECURITY * sec
            + cls.W_ANOMALY * anom
            + cls.W_PERFORMANCE * perf
            + cls.W_HISTORICAL * hist
        )
        composite = round(max(0.0, min(100.0, composite)), 2)

        # Categorize into standard tiers
        category = cls.categorize_score(composite)

        rationale = (
            f"Risk {composite:.1f} ({category.value}): "
            f"Sec={sec:.1f} (40%), Anom={anom:.1f} (25%), "
            f"Perf={perf:.1f} (20%), Hist={hist:.1f} (15%)"
        )

        return RiskEvaluationResult(
            overall_score=composite,
            risk_category=category,
            security_risk=sec,
            anomaly_score=anom,
            performance_risk=perf,
            historical_risk=hist,
            breakdown_rationale=rationale,
        )

    @staticmethod
    def categorize_score(score: float) -> RiskCategory:
        """Map numerical score to standard NetMind RiskCategory tier."""
        if score <= 25.0:
            return RiskCategory.LOW
        elif score <= 50.0:
            return RiskCategory.MEDIUM
        elif score <= 75.0:
            return RiskCategory.HIGH
        else:
            return RiskCategory.CRITICAL

    @classmethod
    def evaluate_flow_risk(
        cls,
        attack_type: str,
        confidence: float,
        anomaly_score: float,
        bytes_per_sec: float,
        packets_per_sec: float,
        is_quarantined_host: bool = False,
    ) -> RiskEvaluationResult:
        """Compute comprehensive risk score directly from real-time flow telemetry metrics.

        Args:
            attack_type: Predicted class name ('Normal', 'DoS', 'Port Scan', etc.).
            confidence: Model probability confidence in [0, 1].
            anomaly_score: Isolation Forest score in [0, 1].
            bytes_per_sec: Current flow byte rate.
            packets_per_sec: Current flow packet rate.
            is_quarantined_host: Whether the host was previously flagged or quarantined.
        """
        # 1. Security Risk Component
        base_threat = cls.ATTACK_BASE_SCORES.get(attack_type, 30.0)
        security_risk = base_threat * confidence

        # 2. Anomaly Risk Component (scale [0, 1] to [0, 100])
        anom_risk = anomaly_score * 100.0

        # 3. Performance Stress Component
        # Benchmark thresholds: > 10,000 pkts/s or > 10 MB/s indicates severe saturation
        pps_stress = min(100.0, (packets_per_sec / 10000.0) * 100.0)
        bps_stress = min(100.0, (bytes_per_sec / 10000000.0) * 100.0)
        performance_risk = max(pps_stress, bps_stress)

        # 4. Historical Risk Component
        historical_risk = 80.0 if is_quarantined_host else 10.0

        return cls.calculate_risk_score(
            security_risk=security_risk,
            anomaly_score=anom_risk,
            performance_risk=performance_risk,
            historical_risk=historical_risk,
        )

    @classmethod
    def generate_recommendations(
        cls,
        attack_type: str,
        confidence: float,
        risk_result: RiskEvaluationResult,
        source_ip: str,
        destination_ip: str,
        dst_port: int,
    ) -> List[RecommendedMitigation]:
        """Rule-based engine mapping attack signatures and risk tiers to actionable mitigation steps.

        Cybersecurity Rationale:
        Translates machine learning outputs into standardized incident response playbooks
        aligned with NIST SP 800-61 (Computer Security Incident Handling Guide).
        """
        recs: List[RecommendedMitigation] = []
        cat = risk_result.risk_category

        # Rule 1: Volumetric Denial of Service (DoS)
        if attack_type == "DoS":
            if cat in (RiskCategory.HIGH, RiskCategory.CRITICAL):
                recs.append(
                    RecommendedMitigation(
                        action=RecommendationAction.RATE_LIMIT_PORT,
                        action_str="RATE_LIMIT_PORT",
                        reason=f"High-volume DoS detected from {source_ip} (Confidence {confidence:.1%}). Rate limit destination service port {dst_port} to prevent upstream connection pool starvation.",
                        urgency="IMMEDIATE",
                        target_entity=f"port:{dst_port}",
                    )
                )
                recs.append(
                    RecommendedMitigation(
                        action=RecommendationAction.BLOCK_SOURCE_IP,
                        action_str="BLOCK_SOURCE_IP",
                        reason=f"Apply perimeter BGP blackhole or edge firewall drop rule for attacking IP {source_ip}.",
                        urgency="IMMEDIATE",
                        target_entity=f"ip:{source_ip}",
                    )
                )

        # Rule 2: Reconnaissance & Port Scanning
        elif attack_type == "Port Scan":
            urgency = "HIGH" if cat in (RiskCategory.HIGH, RiskCategory.CRITICAL) else "ROUTINE"
            recs.append(
                RecommendedMitigation(
                    action=RecommendationAction.BLOCK_SOURCE_IP,
                    action_str="BLOCK_SOURCE_IP",
                    reason=f"Reconnaissance port sweep observed from {source_ip} (Risk {risk_result.overall_score:.1f}). Temporarily drop connection attempts to suppress target mapping.",
                    urgency=urgency,
                    target_entity=f"ip:{source_ip}",
                )
            )

        # Rule 3: Credential Stuffing & Brute Force
        elif attack_type == "Brute Force":
            recs.append(
                RecommendedMitigation(
                    action=RecommendationAction.LOCK_USER_CREDENTIALS,
                    action_str="LOCK_USER_CREDENTIALS",
                    reason=f"Repeated authentication failures detected from {source_ip} targeting port {dst_port}. Invalidate active auth tokens and enforce MFA step-up.",
                    urgency="HIGH",
                    target_entity=f"service:{dst_port}",
                )
            )
            recs.append(
                RecommendedMitigation(
                    action=RecommendationAction.QUARANTINE_HOST,
                    action_str="QUARANTINE_HOST",
                    reason=f"Isolate host {source_ip} into guest VLAN pending forensic review of credential abuse.",
                    urgency="HIGH",
                    target_entity=f"ip:{source_ip}",
                )
            )

        # Rule 4: Web Application Attack (SQLi / XSS / Traversal)
        elif attack_type == "Web Attack":
            recs.append(
                RecommendedMitigation(
                    action=RecommendationAction.WAF_BLOCK_URI_PATTERN,
                    action_str="WAF_BLOCK_URI_PATTERN",
                    reason=f"Exploit payload detected in web request from {source_ip} to {destination_ip}:{dst_port}. Push virtual patch to Web Application Firewall (WAF) rule chain.",
                    urgency="IMMEDIATE",
                    target_entity=f"waf:rule_{dst_port}",
                )
            )

        # Rule 5: Unsupervised High-Score Anomaly (Zero-Day / Novel Threat)
        elif risk_result.anomaly_score >= 60.0 and attack_type == "Normal":
            recs.append(
                RecommendedMitigation(
                    action=RecommendationAction.DEEP_PACKET_INSPECTION,
                    action_str="DEEP_PACKET_INSPECTION",
                    reason=f"Flow deviates significantly from normal baseline (Anomaly Score: {risk_result.anomaly_score:.1f}%), but matches no known attack signatures. Trigger full PCAP packet capture for SOC threat hunting.",
                    urgency="HIGH",
                    target_entity=f"flow:{source_ip}->{destination_ip}",
                )
            )

        # Rule 6: Normal Baseline Activity
        else:
            recs.append(
                RecommendedMitigation(
                    action=RecommendationAction.MONITOR_BASELINE,
                    action_str="MONITOR_BASELINE",
                    reason=f"Flow metrics conform to benign enterprise behavior (Risk: {risk_result.overall_score:.1f}, Category: {cat.value}). Continue passive telemetry recording.",
                    urgency="ROUTINE",
                    target_entity=f"ip:{source_ip}",
                    requires_human_approval=False,
                )
            )

        return recs
