"""NetMind AI - Telemetry Rate Predictions API Router."""

from __future__ import annotations

from typing import Optional

from fastapi import APIRouter, Depends, Query
from sqlalchemy.orm import Session

from netmind.src.backend.database import get_db
from netmind.src.backend.repository import PredictionRepository
from netmind.src.backend.schemas import PaginatedResponse, PredictionRead

router = APIRouter(prefix="/api", tags=["Predictions & Forecasting"])


@router.get("/predictions", response_model=PaginatedResponse)
def list_predictions(
    page: int = Query(1, ge=1, description="Page number"),
    page_size: int = Query(20, ge=1, le=100, description="Items per page"),
    target: Optional[str] = Query(None, description="Target metric: bytes_per_second, packets_per_second"),
    db: Session = Depends(get_db),
) -> PaginatedResponse:
    """Retrieve time-series traffic rate forecasts generated by the model."""
    repo = PredictionRepository(db)
    skip = (page - 1) * page_size
    items, total = repo.list_predictions(skip=skip, limit=page_size, target=target)

    pydantic_items = [PredictionRead.model_validate(item) for item in items]
    total_pages = (total + page_size - 1) // page_size if total > 0 else 0

    return PaginatedResponse(
        total=total,
        page=page,
        page_size=page_size,
        pages=total_pages,
        items=pydantic_items,
    )
