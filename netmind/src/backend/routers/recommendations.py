"""NetMind AI - Mitigation Recommendations API Router."""

from __future__ import annotations

from typing import Optional

from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session

from netmind.src.backend.database import get_db
from netmind.src.backend.repository import RecommendationRepository
from netmind.src.backend.schemas import (
    PaginatedResponse,
    RecommendationRead,
    ReviewRecommendationRequest,
)

router = APIRouter(prefix="/api", tags=["Mitigation Recommendations"])


@router.get("/recommendations", response_model=PaginatedResponse)
def list_recommendations(
    page: int = Query(1, ge=1, description="Page number"),
    page_size: int = Query(20, ge=1, le=100, description="Items per page"),
    status: Optional[str] = Query(None, description="Filter by status: pending, approved, rejected, applied"),
    db: Session = Depends(get_db),
) -> PaginatedResponse:
    """Retrieve actionable containment recommendations generated by the Decision Engine."""
    repo = RecommendationRepository(db)
    skip = (page - 1) * page_size
    items, total = repo.list_recommendations(skip=skip, limit=page_size, status=status)

    pydantic_items = [RecommendationRead.model_validate(item) for item in items]
    total_pages = (total + page_size - 1) // page_size if total > 0 else 0

    return PaginatedResponse(
        total=total,
        page=page,
        page_size=page_size,
        pages=total_pages,
        items=pydantic_items,
    )


@router.post("/recommendations/{recommendation_id}/review", response_model=RecommendationRead)
def review_recommendation(
    recommendation_id: int,
    req: ReviewRecommendationRequest,
    db: Session = Depends(get_db),
) -> RecommendationRead:
    """Approve, reject, or mark as applied a proposed containment mitigation."""
    repo = RecommendationRepository(db)
    rec = repo.review(
        rec_id=recommendation_id,
        decision_status=req.status.value,
        reviewed_by=req.reviewed_by,
    )
    if not rec:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Recommendation with ID {recommendation_id} not found",
        )
    return RecommendationRead.model_validate(rec)
